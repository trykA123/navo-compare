//! Tests for lock drift parsing and comparison against another lockfile.

use std::collections::BTreeSet;

use crate::lock_drift::{Drift, Report, Versions, compare, versions};

/// A lockfile with two sourced packages, used by several tests.
const TWO_PACKAGES: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "a"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "b"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

/// Parses `text` and panics with the line number when it is malformed.
fn parsed(text: &str) -> Versions {
    versions(text).unwrap_or_else(|line| panic!("malformed at line {line}"))
}

/// Asserts one drift with exactly the given sorted versions.
fn assert_drift(report: &Report, name: &str, ours: &[&str], theirs: &[&str]) {
    assert_eq!(
        report.drifts,
        vec![Drift {
            name: name.to_owned(),
            ours: ours.iter().map(|value| (*value).to_owned()).collect(),
            theirs: theirs.iter().map(|value| (*value).to_owned()).collect(),
        }]
    );
}

/// Equal lockfiles have every package shared and no drift.
#[test]
fn equal_files_have_no_drift() {
    let ours = parsed(TWO_PACKAGES);
    let report = compare(&ours, &ours);
    assert_eq!(report.shared, 2);
    assert!(report.drifts.is_empty());
}

/// Our 1.0.0 is held by theirs at 1.0.0 and 2.0.0, so nothing drifts.
#[test]
fn our_older_version_present_on_their_side_does_not_drift() {
    let ours = parsed(
        r#"[[package]]
name = "a"
version = "1.0.0"
source = "registry+x"
"#,
    );
    let theirs = parsed(
        r#"[[package]]
name = "a"
version = "1.0.0"
source = "registry+x"

[[package]]
name = "a"
version = "2.0.0"
source = "registry+x"
"#,
    );
    let report = compare(&ours, &theirs);
    assert_eq!(report.shared, 1);
    assert!(report.drifts.is_empty());
}

/// Our 1.0.1 is not held by theirs at 1.0.0, so it drifts.
#[test]
fn a_newer_our_version_drifts() {
    let ours = parsed(
        r#"[[package]]
name = "a"
version = "1.0.1"
source = "registry+x"
"#,
    );
    let theirs = parsed(
        r#"[[package]]
name = "a"
version = "1.0.0"
source = "registry+x"
"#,
    );
    let report = compare(&ours, &theirs);
    assert_eq!(report.shared, 1);
    assert_drift(&report, "a", &["1.0.1"], &["1.0.0"]);
}

/// Two versions on our side drift when one of them is not theirs.
#[test]
fn two_our_versions_with_one_shared_still_drift() {
    let ours = parsed(
        r#"[[package]]
name = "a"
version = "1.0.0"
source = "registry+x"

[[package]]
name = "a"
version = "2.0.0"
source = "registry+x"
"#,
    );
    let theirs = parsed(
        r#"[[package]]
name = "a"
version = "1.0.0"
source = "registry+x"
"#,
    );
    let report = compare(&ours, &theirs);
    assert_eq!(report.shared, 1);
    assert_drift(&report, "a", &["1.0.0", "2.0.0"], &["1.0.0"]);
}

/// A package name only on one side is not shared and never drifts.
#[test]
fn a_name_on_one_side_is_not_shared() {
    let ours = parsed(
        r#"[[package]]
name = "left"
version = "1.0.0"
source = "registry+x"
"#,
    );
    let theirs = parsed(
        r#"[[package]]
name = "right"
version = "1.0.0"
source = "registry+x"
"#,
    );
    let report = compare(&ours, &theirs);
    assert_eq!(report.shared, 0);
    assert!(report.drifts.is_empty());
}

/// A package table without a version is malformed at its table line.
#[test]
fn a_package_without_a_version_is_malformed() {
    let text = "version = 4\n\n[[package]]\nname = \"broken\"\nsource = \"registry+x\"\n";
    assert_eq!(versions(text).unwrap_err(), 3);
}

/// A package without a source is a workspace crate and is left out.
#[test]
fn a_package_without_a_source_is_left_out() {
    let text = r#"[[package]]
name = "xtask"
version = "0.1.0"

[[package]]
name = "xtask"
version = "0.2.0"
"#;
    let versions = parsed(text);
    assert!(versions.is_empty());
    let report = compare(&versions, &versions);
    assert_eq!(report.shared, 0);
    assert!(report.drifts.is_empty());
}

/// Drifts come out sorted by package name.
#[test]
fn drifts_are_sorted_by_name() {
    let ours = parsed(
        r#"[[package]]
name = "z"
version = "1.0.0"
source = "registry+x"

[[package]]
name = "a"
version = "1.0.0"
source = "registry+x"

[[package]]
name = "m"
version = "1.0.0"
source = "registry+x"
"#,
    );
    let theirs = parsed(
        r#"[[package]]
name = "z"
version = "0.0.1"
source = "registry+x"

[[package]]
name = "a"
version = "0.0.1"
source = "registry+x"

[[package]]
name = "m"
version = "0.0.1"
source = "registry+x"
"#,
    );
    let report = compare(&ours, &theirs);
    let names: Vec<&str> = report
        .drifts
        .iter()
        .map(|drift| drift.name.as_str())
        .collect();
    assert_eq!(names, ["a", "m", "z"]);
    assert_eq!(report.shared, 3);
}

/// CRLF line ends are trimmed before keys are read.
#[test]
fn crlf_line_ends_are_trimmed() {
    let text = "# lock\r\nversion = 4\r\n\r\n[[package]]\r\nname = \"a\"\r\nversion = \"1.0.0\"\r\nsource = \"registry+x\"\r\n";
    let versions = parsed(text);
    let expected = BTreeSet::from(["1.0.0".to_owned()]);
    assert_eq!(versions.get("a"), Some(&expected));
}
